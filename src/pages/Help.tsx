function FaqItem({ title, answer }: { title: string; answer: string }) {
  const [open, setOpen] = useState(false)
  return (
    <div
      style={{
        background: 'var(--surface)',
        border: '1px solid var(--border)',
        borderRadius: 14,
        overflow: 'hidden',
        transition: 'border-color .15s',
      }}
    >
      <button
        onClick={() => setOpen((o) => !o)}
        style={{
          width: '100%',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: 12,
          padding: '16px 20px',
          background: 'none',
          border: 'none',
          cursor: 'pointer',
          textAlign: 'left',
          fontFamily: 'inherit',
        }}
      >
        <span style={{ fontSize: 15, fontWeight: 600, color: 'var(--text)', lineHeight: 1.4 }}>
          {title}
        </span>
        <span
          style={{
            flexShrink: 0,
            color: 'var(--indigo-400)',
            transform: open ? 'rotate(180deg)' : 'rotate(0deg)',
            transition: 'transform .2s ease',
            display: 'flex',
          }}
        >
          <ChevronDown size={18} />
        </span>
      </button>
      {open && (
        <div
          style={{
            padding: '0 20px 18px',
            fontSize: 14,
            color: 'var(--text-2)',
            lineHeight: 1.7,
            borderTop: '1px solid var(--border)',
            paddingTop: 14,
          }}
        >
          {answer}
        </div>
      )}
    </div>
  )
}

